#!/usr/bin/env bash
# Сверить кит на диске с общим репозиторием. Запуск из корня проекта,
# без аргументов: claude-kit/check-kit.sh
#
# Кит подключён подмодулем и общий с другими проектами, поэтому расходиться он
# может в обе стороны, и обе тихие:
#   • в репозиторий приехало чужое исправление, а у нас старая версия;
#   • у нас правка, которой нет в репозитории, — её снесёт первое же обновление.
#
# Отдельно проверяется то, что легче всего пропустить: коммит, записанный
# в родительском репозитории, может не совпадать с тем, что лежит в рабочей
# копии. Тогда у нас на диске всё верно, а склонировавший проект получит старое.
# В git submodule status такое помечается плюсом перед хешем.
#
# Код возврата: 0 — всё сходится, 1 — есть что сделать руками.

set -uo pipefail
# Корень проекта — родитель кита, а не каталог скрипта: скрипт лежит ВНУТРИ
# подмодуля, и git submodule status работает только из родительского репозитория.
cd "$(dirname "$(realpath "${BASH_SOURCE[0]:-$0}")")/.." 

KIT="$(basename "$(dirname "$(realpath "${BASH_SOURCE[0]:-$0}")")")"
problems=0
say() { printf '%s\n' "$1"; }
bad() { printf '  ! %s\n' "$1"; problems=$((problems + 1)); }

[ -d "$KIT/.git" ] || [ -f "$KIT/.git" ] || { say "кита нет в ${PWD}/${KIT}"; exit 1; }

# Без fetch сравнивать не с чем: origin/main без него показывает то, что было
# при последнем обращении к сети, и «расхождений нет» означало бы «мы давно
# не смотрели», а не «мы в курсе».
if ! err="$(git -C "$KIT" fetch --quiet origin 2>&1)"; then
  say "не удалось связаться с репозиторием кита:"
  say "  ${err:-без объяснения}"
  say "Сверка не выполнена — это не то же самое, что «расхождений нет»."
  exit 1
fi

local_head="$(git -C "$KIT" rev-parse HEAD)"
remote_head="$(git -C "$KIT" rev-parse origin/main)"
behind="$(git -C "$KIT" rev-list --count HEAD..origin/main)"
ahead="$(git -C "$KIT" rev-list --count origin/main..HEAD)"

say "кит: $(git -C "$KIT" log --oneline -1 HEAD)"
say "репозиторий: $(git -C "$KIT" log --oneline -1 origin/main)"

if [ "$local_head" != "$remote_head" ]; then
  [ "$behind" -gt 0 ] && bad "отстаём на ${behind} коммит(ов): git -C ${KIT} pull origin main"
  [ "$ahead" -gt 0 ] && bad "у нас ${ahead} коммит(ов), которых нет в репозитории: их снесёт обновление"
fi

# Незакоммиченные правки внутри кита — самое дорогое из тихого: они выглядят
# работающими ровно до следующего обновления подмодуля.
if [ -n "$(git -C "$KIT" status --porcelain)" ]; then
  bad "внутри кита есть незакоммиченные изменения — закоммитить в его репозиторий, иначе пропадут:"
  git -C "$KIT" status --short | sed 's/^/      /'
fi

# Плюс перед хешем: рабочая копия и запись в родителе разошлись.
if git submodule status "$KIT" | grep -q '^+'; then
  bad "родительский репозиторий записан на другой коммит кита: git add ${KIT} && git commit"
fi

if [ "$problems" -eq 0 ]; then
  say "расхождений нет"
  exit 0
fi
exit 1
