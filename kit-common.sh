#!/usr/bin/env bash
# Общее для всех shell-скриптов кита: где корень проекта, где настройки, где состояние.
# Подключается через source. Сам ничего не делает и ничего не проверяет —
# проверку заказывает вызывающий через kit_require, потому что разным скриптам
# нужны разные ключи: обходу хватает названия проекта, мосту нужен чат и токен.
#
# Python-двойник — tg/kitconf.py. Оба ищут корень одним и тем же способом и читают
# один и тот же project.conf, и в этом весь смысл: настройка проекта живёт в одном
# месте. Меняешь поиск здесь — меняй и там, иначе bash и Python разойдутся молча.

# Под zsh этот файл не работает и работать не может: kit_require построен на
# косвенном раскрытии ${!v}, а zsh отвечает на него «bad substitution».
# Поэтому обрываемся здесь, внятно, а не там, где симптом уже не связан с причиной.
#
# Без этой проверки zsh ломался тихо и уводил в сторону. BASH_SOURCE в нём нет,
# dirname от пустой строки даёт «.», KIT_DIR становится корнем проекта, поиск
# настроек стартует на уровень выше и промахивается. В итоге на глаза попадало
# «ни в одном каталоге над <корень> нет project.conf» — при том что project.conf
# лежит ровно в этом корне, — и совет создать его этажом выше, то есть заведомо
# не там. Проверено: на macOS zsh стоит по умолчанию, и Bash-тул Claude Code
# гоняет команды тоже в нём, так что наступает на это каждый, кто выполнит
# строчку из документации буквально.
if [ -n "${ZSH_VERSION:-}" ]; then
  echo "kit-common.sh нельзя подключать из zsh — он рассчитан на bash." >&2
  echo "Вызывай так: bash -c 'source claude-kit/kit-common.sh && <команда>'" >&2
  return 1 2>/dev/null || exit 1
fi

# ${BASH_SOURCE[0]:-$0} вместо голого BASH_SOURCE: при запуске файла напрямую,
# а не через source, массив пуст, и путь считался бы от пустой строки.
KIT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"

# Корень проекта ищется ВВЕРХ ОТ КИТА по признаку «здесь лежит project.conf».
#
# Почему не «родитель кита»: кит подключается git-подмодулем и может оказаться
# не в корне, а, скажем, в tools/claude-kit. Привязка к родительскому каталогу
# сломалась бы молча — скрипты стали бы искать настройки и dialog/ не там.
#
# Почему поиск начинается с родителя, а не с самого кита: project.conf внутри кита
# лежать не должен. Кит общий для всех проектов, настройки у каждого свои; файл,
# оставленный внутри, при обновлении подмодуля затрётся или уедет в чужой проект.
kit_find_root() {
  local d="$1"
  while [ "$d" != "/" ] && [ -n "$d" ]; do
    [ -f "$d/project.conf" ] && { printf '%s\n' "$d"; return 0; }
    d="$(dirname "$d")"
  done
  return 1
}

if [ -n "${KIT_PROJECT_ROOT:-}" ]; then
  # Явное указание корня. Нужно для проверок и для нестандартных раскладок,
  # когда искать по project.conf нечего или не хочется.
  KIT_ROOT="$(cd "$KIT_PROJECT_ROOT" 2>/dev/null && pwd)" || {
    echo "KIT_PROJECT_ROOT указывает на несуществующий каталог: ${KIT_PROJECT_ROOT}" >&2
    exit 1
  }
else
  KIT_ROOT="$(kit_find_root "$(dirname "$KIT_DIR")" || true)"
fi

if [ -z "${KIT_ROOT:-}" ]; then
  echo "не найден корень проекта: ни в одном каталоге над ${KIT_DIR} нет project.conf" >&2
  echo "создать: cp ${KIT_DIR}/project.conf.example $(dirname "$KIT_DIR")/project.conf и заполнить" >&2
  exit 1
fi

KIT_CONF="$KIT_ROOT/project.conf"

# Рабочее состояние — тоже не часть кита: offset приёмника и указатель на сокет
# принадлежат проекту и переживают переустановку подмодуля. Лежат в корне проекта
# ровно поэтому: удаление и повторное добавление claude-kit их не задевает.
KIT_STATE_DIR="${KIT_STATE_DIR:-$KIT_ROOT/.kit-state}"

if [ ! -f "$KIT_CONF" ]; then
  echo "нет файла настроек ${KIT_CONF}" >&2
  echo "создать: cp ${KIT_DIR}/project.conf.example ${KIT_CONF} и заполнить" >&2
  exit 1
fi

# Забытый project.conf внутри кита — частая ошибка по старой памяти: человек правит
# его, ничего не меняется, и причина не видна. Поэтому о нём говорится вслух.
if [ -f "$KIT_DIR/project.conf" ]; then
  echo "ВНИМАНИЕ: ${KIT_DIR}/project.conf игнорируется — настройки читаются из ${KIT_CONF}" >&2
fi

# shellcheck source=/dev/null
source "$KIT_CONF"

# Проверка, что нужные ключи заполнены. Незаполненным считается пустое значение
# и оставшийся <плейсхолдер>: без этой проверки скрипт уходит работать с мусором
# и падает потом, в неочевидном месте и с невнятной ошибкой.
#
# Плейсхолдер ищется в любом месте значения, а не только целиком: в шаблоне есть
# ключи вида «telegram-bot-token-<проект>», и заполненными наполовину они выглядят
# правдоподобно ровно до первого обращения к Keychain.
kit_require() {
  local v val missing=""
  for v in "$@"; do
    val="${!v:-}"
    case "$val" in
      "" | *"<"*">"*) missing="${missing}  ${v}"$'\n' ;;
    esac
  done
  if [ -n "$missing" ]; then
    echo "в ${KIT_CONF} не заполнены настройки:" >&2
    printf '%s' "$missing" >&2
    echo "заполни их и повтори; пояснения — в ${KIT_DIR}/project.conf.example" >&2
    exit 1
  fi
}
